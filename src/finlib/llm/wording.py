"""Запрещённые формулировки: отсылки к нормативу, которого в методике нет.

Постпроверка чисел защищает только числовые утверждения. Фраза «коэффициент
текущей ликвидности 0,82, что ниже норматива 1,0» её проходит: 0,82 взято
из блоков, а 1,0 разрешено без привязки как тривиальное. Между тем методика
абсолютных нормативов не содержит принципиально — опорные точки шкал объявлены
экспертной калибровкой, — и модель вернула норматив текстом.

Словарь обходится перефразировкой, и это не повод его не иметь: обходится он
намеренно, а нарушения происходят случайно.
"""

import re
from dataclasses import dataclass

# Порог, названный нормативом или требованием. Корни, а не точные формы:
# русские слова склоняются, а запрещено само понятие.
_PATTERNS: tuple[tuple[str, str], ...] = (
    (r"нормативн\w*|\bнорматив\w*", "норматив"),
    (r"при\s+норме\b|\bнорме\s+не\s+менее|\bнорма\s+составляет", "норма"),
    (r"рекомендуем\w*\s+значени\w*|рекомендуем\w*\s+уровн\w*", "рекомендуемое значение"),
    (r"должен\s+быть\s+не\s+(?:менее|более)|должна\s+быть\s+не\s+(?:менее|более)", "требование"),
    (
        r"(?:не\s+)?соответству\w*\s+норм\w*|(?:не\s+)?отвечает\s+норм\w*",
        "соответствие норме",
    ),
    (r"общепринят\w*\s+(?:порог\w*|значени\w*|уровн\w*)", "общепринятый порог"),
    (r"пороговое\s+значение|критическое\s+значение\s+составляет", "пороговое значение"),
    # Порог без слова «норматив»: тот же запрет другими словами. «Не менее»
    # и «не более» в наших собственных текстах блоков не встречаются ни разу,
    # поэтому запрет не заденет цитирование готовых формулировок.
    (r"\bне\s+(?:менее|более)\b", "порог «не менее / не более»"),
    (
        r"\bдолж(?:ен|на|но|ны)\b[\s\w]{0,20}?(?:составля\w*|превыша\w*|быть)",
        "требование к величине",
    ),
    (r"минимально\s+допустим\w*|максимально\s+допустим\w*", "допустимый предел"),
    (
        r"(?:безопасн\w*|приемлем\w*|достаточн\w*|нормальн\w*|здоров\w*)"
        r"\s+(?:счита\w*|уровн\w*|значени\w*|диапазон\w*)",
        "оценочный уровень",
    ),
)

_COMPILED: tuple[tuple[re.Pattern[str], str], ...] = tuple(
    (re.compile(pattern, re.IGNORECASE), label) for pattern, label in _PATTERNS
)


@dataclass(frozen=True, slots=True)
class Wording:
    """Найденная запрещённая формулировка."""

    text: str
    label: str
    context: str

    def describe(self) -> str:
        """Человеческое объяснение, чем формулировка плоха."""
        return (
            f"«{self.text}» — отсылка к нормативу ({self.label}); "
            "методика абсолютных нормативов не содержит"
        )


def find_forbidden(text: str) -> list[Wording]:
    """Все отсылки к нормативу в тексте ответа."""
    found: list[Wording] = []
    for pattern, label in _COMPILED:
        for match in pattern.finditer(text):
            found.append(
                Wording(match.group(), label, _context_of(text, match.span()))
            )
    return sorted(found, key=lambda item: item.context)


def _context_of(text: str, span: tuple[int, int], width: int = 60) -> str:
    """Окружение формулировки — чтобы в журнале было видно, где она появилась."""
    start = max(0, span[0] - width)
    end = min(len(text), span[1] + width)
    return " ".join(text[start:end].split())
