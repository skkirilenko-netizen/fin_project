"""Единственная точка подстановки нуля вместо нераскрытого значения.

Инвариант 4 допускает две трактовки нераскрытого значения, и смешивать их
нельзя. При **проверке арифметики итога** нераскрытая строка считается нулём:
иначе контроль сходимости разваливается на любой упрощённой форме, где
организация раскрывает три строки из семи. При **расчёте коэффициентов**
нераскрытое значение остаётся None, показатель получает not_calculable,
подстановка нуля запрещена.

Поэтому подстановка живёт здесь и только здесь. Модуль metrics/ эту функцию
не импортирует — это проверяется тестом, а не соглашением.
"""

from decimal import Decimal


def as_addend(value: Decimal | None) -> Decimal:
    """Слагаемое для проверки сходимости итога: нераскрытое считается нулём."""
    return Decimal(0) if value is None else value


def is_disclosed(value: Decimal | None) -> bool:
    """Раскрыто ли значение. Ноль раскрытый и отсутствие значения — разные вещи."""
    return value is not None
