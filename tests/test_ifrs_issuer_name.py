"""Наименование эмитента читается строением документа, а не первым совпадением.

У комплектов МСФО наименования организации в базе не было вовсе: ни один путь
загрузки его не читал, и заключение по ФосАгро выходило с ИНН в шапке.

Опора структурная — титульный лист и колонтитул, — и она же отводит чужой
ответ: наименование аудитора стоит в заключении и повторяется в нём, а через
формы проходит только колонтитул эмитента. Без этого различения первое
измерение дало трёх аудиторов вместо эмитентов: «АО «Кэпт»» у Норникеля,
«ООО «Б1 – Аудит»» у Европлана и Самолёта.
"""

from finlib.sources.ifrs_document import issuer_name

TITLE = """
ПАО «Эмитент»

Консолидированная финансовая отчётность
в соответствии со стандартами МСФО и Аудиторское заключение
независимого аудитора

31 декабря 2025 года

Аудиторское заключение независимого аудитора
Акционерам и Совету директоров ПАО «Эмитент»
АО «Аудитор»
АО «Аудитор»
АО «Аудитор»
"""

FORMS = """
ПАО «Эмитент»
Консолидированный отчёт о финансовом положении
Итого активы 1 000 000
ПАО «Эмитент»
Консолидированный отчёт о прибыли или убытке
Выручка 900 000
"""


def test_name_comes_from_the_running_header() -> None:
    """Наименование эмитента — то, что проходит колонтитулом через формы."""
    text = TITLE + FORMS
    assert issuer_name(text, before=len(TITLE)) == "ПАО «Эмитент»"


def test_auditor_is_not_mistaken_for_the_issuer() -> None:
    """Наименование аудитора эмитентом не становится, даже если оно чаще.

    В титуле и заключении «АО «Аудитор»» встречается трижды, эмитент —
    дважды; через формы проходит только эмитент.
    """
    text = TITLE + FORMS
    assert issuer_name(text, before=len(TITLE)) != "АО «Аудитор»"


def test_single_occurrence_is_not_a_name() -> None:
    """Единственное вхождение наименованием эмитента не считается.

    Отказ здесь дороже догадки: в отчётности называются дочерние общества,
    банки и контрагенты, и по одному упоминанию эмитента от них не отличить.
    Документ тогда выходит с ИНН в шапке — это верно, а чужое наименование
    было бы ложью.
    """
    text = TITLE + "\nПАО «Эмитент»\nИтого активы 1 000 000\n"
    assert issuer_name(text, before=len(TITLE)) is None
