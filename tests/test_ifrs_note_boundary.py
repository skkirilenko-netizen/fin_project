"""Тесты границы между формами и примечаниями.

**Строка примечания в очереди разметки форм — это будущее задвоение итога.**
У О'КЕЙ страница с отчётом о прибыли или убытке не имеет текстового слоя,
и заголовком формы стала проза примечания — «Сравнительные показатели отчёта
о прибыли или убытке… были пересчитаны», за которой идёт таблица прекращённой
деятельности. Блоком формы становилось примечание целиком: выручкой комплекта
оказывалась выручка прекращённой деятельности, 52 756 406 вместо настоящей,
а одиннадцать строк примечания уходили в очередь разметки основных форм.

Второй случай того же рода — с обратной стороны: у Европлана нумерованный
абзац аудиторского заключения «1. Мы не имели возможности получить…»
становился первым примечанием, и тогда внутри примечаний оказывались все формы
сразу. Отсчёт примечаний поэтому ведётся от первой найденной формы.
"""

from datetime import date

from finlib.normalize.ifrs_lines import load_ifrs_lines
from finlib.sources.ifrs_extract import extract
from finlib.sources.ifrs_inbox import form_blocks, form_headings, load_parsing_policy
from finlib.sources.ifrs_notes import first_note_start, index_notes
from finlib.sources.ifrs_numbers import Grouping

DATES = (date(2025, 12, 31), date(2024, 12, 31))

FORMS = """
Консолидированный отчёт о финансовом положении
(в миллионах российских рублей)
Пояснения      31 декабря 2025 года      31 декабря 2024 года
Основные средства 700 000 650 000
Итого внеоборотные активы 700 000 650 000
Запасы 200 000 180 000
Денежные средства и их эквиваленты 100 000 90 000
Итого оборотные активы 300 000 270 000
Итого активы 1 000 000 920 000

Консолидированный отчёт о движении денежных средств
(в миллионах российских рублей)
Прибыль до налогообложения 260 000 220 000
Амортизация 30 000 28 000
Проценты уплаченные (50 000) (48 000)
Налог на прибыль уплаченный (52 000) (44 000)
Денежные средства от операционной деятельности 188 000 156 000
Приобретение основных средств (90 000) (80 000)
"""

# Примечания. В одном из них проза называет форму, и за прозой идёт таблица —
# ровно случай О'КЕЙ.
NOTES = """
1 Общие сведения
Группа зарегистрирована в Российской Федерации и занимается розничной
торговлей продуктами питания.

2 Прекращённая деятельность
Сравнительные показатели отчёта о прибыли или убытке и прочем совокупном
доходе были пересчитаны, чтобы представить прекращённую деятельность
отдельно от продолжающейся деятельности.
(a) Результаты прекращённой деятельности
тыс. руб. 2025 2024
Выручка 52 756 406 73 441 366
Элиминирование выручки от межсегментных продаж (96 284) (1 050 479)
Выручка от продаж внешним покупателям 52 660 122 72 390 887
Расходы (49 097 418) (72 260 720)
Внешние расходы (48 860 813) (71 045 746)
Результаты операционной деятельности 3 799 309 1 345 141
Налог на прибыль (833 821) 623 283
"""

AUDIT = """
Аудиторское заключение независимых аудиторов
Основание для выражения мнения с оговоркой
1. Мы не имели возможности получить достаточные надлежащие аудиторские
доказательства относительно корректности раскрытия информации о наличии
или отсутствии стороны, обладающей конечным контролем, поскольку Общество
такой информацией не располагает.
2. В прилагаемой консолидированной финансовой отчётности Группа не раскрыла
сведения, требуемые стандартом, о связанных сторонах и операциях с ними.
"""


def headings_of(text: str) -> dict[str, int]:
    """Заголовки форм документа."""
    return form_headings(text, load_ifrs_lines(), load_parsing_policy())


def test_form_heading_is_not_taken_from_a_note() -> None:
    """Проза примечания, за которой идёт таблица, заголовком формы не является."""
    found = headings_of(FORMS + NOTES)
    assert "ifrs.statement_of_financial_position" in found
    assert "ifrs.statement_of_cash_flows" in found
    # Отчёта о прибыли или убытке в документе нет: его страница пуста,
    # и подменять его таблицей примечания нельзя.
    assert "ifrs.statement_of_profit_or_loss" not in found


def test_note_rows_do_not_reach_the_forms() -> None:
    """Величины примечания не становятся величинами форм.

    Выручка прекращённой деятельности — настоящее число, но выручкой
    комплекта она не является: это тот же класс, что графы чужой
    длительности.
    """
    text = FORMS + NOTES
    found = extract(text, DATES, Grouping.RUSSIAN, layouts=None)
    names = {row.source_name for row in found.unrecognised}
    assert "Расходы" not in names
    assert "Выручка от продаж внешним покупателям" not in names
    assert found.value_of("ifrs.revenue", DATES[0]) is None


def test_form_block_stops_where_the_notes_begin() -> None:
    """Блок формы кончается на примечаниях, даже если таблица не кончилась."""
    text = FORMS + NOTES
    blocks = form_blocks(text, headings_of(text), load_parsing_policy())
    flows = "\n".join(blocks["ifrs.statement_of_cash_flows"])
    assert "Приобретение основных средств" in flows
    assert "Общие сведения" not in flows
    assert "Выручка от продаж внешним покупателям" not in flows


def test_a_form_row_with_a_note_number_is_not_a_note_heading() -> None:
    """Строка формы с номером примечания слева заголовком примечания не является.

    У СИБУРа «4 Активы, предназначенные для продажи 12 605 -» — строка
    баланса, и указатель начинал примечания на шестьдесят тысяч знаков
    раньше настоящего первого. Отличает их наличие величин.
    """
    text = (
        FORMS
        + "\n4 Активы, предназначенные для продажи 12 605 -\n"
        + " Итого активы 1 012 605 920 000\n"
        + NOTES
    )
    index = index_notes(text, None, load_parsing_policy().notes, 0)
    assert 4 not in {item.number for item in index.notes}


def test_audit_paragraph_before_the_forms_is_not_the_first_note() -> None:
    """Нумерованный абзац заключения примечанием не считается.

    Иначе внутри примечаний оказываются все формы сразу, и документ, в котором
    формы есть, объявляется не отчётностью.
    """
    text = AUDIT + FORMS + NOTES
    found = headings_of(text)
    assert "ifrs.statement_of_financial_position" in found
    assert "ifrs.statement_of_cash_flows" in found
    # Отсчёт от первой найденной формы: примечания начинаются после неё.
    start = first_note_start(text, load_parsing_policy().notes, min(found.values()))
    assert start is not None
    assert start > min(found.values())
